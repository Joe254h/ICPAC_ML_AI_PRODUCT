/** The same words keyed in lower case: page banners write names in title case. */
const LOWER: Record<string, Record<string, string>> = Object.fromEntries(
  Object.entries(WORDS).map(([language, words]) => [
    language,
    Object.fromEntries(
      Object.entries(words).map(([text, word]) => [text.toLowerCase(), word]),
    ),
  ]),
);

/** ``text`` in ``language``, or as it is when no translation exists. */
export function translate(text: string, language: string): string {
  if (language === "en") return text;
  return LOWER[language]?.[text.toLowerCase()] ?? text;
}

/** Whether ``text`` has its own word in ``language``. */
export function hasTranslation(text: string, language: string): boolean {
  return text.toLowerCase() in (LOWER[language] ?? {});
}

/** The site's words in the chosen language. */
export function useT(): (text: string) => string {
  const [language] = useLanguage();
  return useCallback((text: string) => translate(text, language), [language]);
}
